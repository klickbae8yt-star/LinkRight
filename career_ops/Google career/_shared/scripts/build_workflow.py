def load_enabled_portals() -> list[dict[str, Any]]:
    portals = []
    for pfile in sorted((ROOT / "portals").glob("*/portal.json")):
        if pfile.parent.name.startswith("_"):
            continue
        cfg = json.loads(pfile.read_text(encoding="utf-8"))
        if cfg.get("enabled", False):
            portals.append(cfg)
    if not portals:
        raise SystemExit("No enabled portals found under portals/*/portal.json")
    return portals


